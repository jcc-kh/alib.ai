#!/usr/bin/env python3
"""Write a Markdown listing of every SQLite database under a folder: tables, row counts, columns.

  python dump_schema.py ../raw/msab-2026/iphone12 > ../datasets/schemas/msab-2026-iphone12.md

Any file that starts with the SQLite header is treated as a database, whatever
its name. Databases are opened read-only with their -wal files. Encrypted or
unreadable files are listed as such. Each database is labelled with its app:
on iOS from the container metadata plist, on Android from the package folder
(with the Android user id when it is not the main user, e.g. the secure folder).
"""
import os
import plistlib
import re
import sqlite3
import sys

root = sys.argv[1]
min_rows = int(sys.argv[2]) if len(sys.argv) > 2 else 1   # hide tables with fewer rows than this
DB = re.compile(r"\.(db|sqlite|sqlite3|sqlitedb|storedata)$", re.I)
SKIP_TABLES = re.compile(r"^(sqlite_|Z_|_Sqlite|.*_fts|.*_content$|.*_docsize$|.*_segments$|.*_segdir$|.*_stat$|.*_idx$|.*_config$|.*_data$)", re.I)

# iOS: map container folders to bundle ids
labels = {}
for d, _, files in os.walk(root):
    for f in files:
        if f.endswith("mobile_container_manager.metadata.plist"):
            try:
                with open(os.path.join(d, f), "rb") as fh:
                    labels[d] = plistlib.load(fh).get("MCMMetadataIdentifier", "")
            except Exception:
                pass


ANDROID = re.compile(r"/userdata/(?:data|user/(\d+)|user_de/(\d+))/([^/]+)/")


def label(path):
    for d, ident in labels.items():
        if path.startswith(d + os.sep):
            return ident
    m = ANDROID.search(path)
    if m:
        user = m.group(1) or m.group(2)
        return m.group(3) + (f" (user {user})" if user and user != "0" else "")
    return ""


def is_sqlite(path):
    try:
        with open(path, "rb") as fh:
            return fh.read(16) == b"SQLite format 3\x00"
    except OSError:
        return False


dbs = sorted(
    os.path.join(d, f) for d, _, files in os.walk(root) for f in files
    if not f.endswith(("-wal", "-shm", "-journal")) and (DB.search(f) or is_sqlite(os.path.join(d, f)))
)
out, shown, empty, unreadable = [], 0, 0, []
for path in dbs:
    rel = os.path.relpath(path, root)
    try:
        con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
        tables = [r[0] for r in con.execute("select name from sqlite_master where type='table' order by name")]
    except sqlite3.Error as e:
        unreadable.append((rel, label(path), str(e)))
        continue
    rows = []
    for t in tables:
        if SKIP_TABLES.search(t):
            continue
        try:
            n = con.execute(f'select count(*) from "{t}"').fetchone()[0]
            cols = [f"{c[1]} {c[2]}".strip() for c in con.execute(f'pragma table_info("{t}")')]
        except sqlite3.Error:
            continue
        if n >= min_rows:
            rows.append((t, n, cols))
    if not rows:
        empty += 1
        continue
    shown += 1
    app = label(path)
    out.append(f"\n### `{rel}`\n")
    out.append(f"{'App: `' + app + '`. ' if app else ''}{os.path.getsize(path) / 1e3:.0f} KB, {len(rows)} tables with data.\n")
    out.append("| Table | Rows | Columns |\n|---|---|---|")
    for t, n, cols in rows:
        out.append(f"| `{t}` | {n} | {', '.join(cols)} |")

print(f"# SQLite schemas: `{os.path.basename(os.path.abspath(root))}`\n")
print("Generated by `scripts/dump_schema.py`. Do not edit by hand.\n")
print(f"- Databases found: {len(dbs)}")
print(f"- Shown below (at least one table with {min_rows}+ rows): {shown}")
print(f"- Empty or system-only: {empty}")
print(f"- Unreadable (encrypted or not SQLite): {len(unreadable)}\n")
print("Only tables with data are listed. Search-index and Core Data bookkeeping tables are left out.")
print("\n".join(out))
if unreadable:
    print("\n## Unreadable databases\n\n| File | App | Error |\n|---|---|---|")
    for rel, app, err in unreadable:
        print(f"| `{rel}` | {app} | {err} |")
