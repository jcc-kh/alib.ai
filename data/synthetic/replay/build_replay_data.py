#!/usr/bin/env python3
"""Extract the evening of 16 April from the Pier 9 bundle into replay-data.js for the scene replay page.

    python build_replay_data.py

Everything shown in the replay comes from the phone files: location fixes, messages and calls between
the five people, and power events. Nothing is typed in by hand except the names and colours.
"""
import json
import os
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
BUNDLE = os.path.join(HERE, "..", "pier9")
START, END = datetime.fromisoformat("2026-04-16T18:00:00-04:00"), datetime.fromisoformat("2026-04-17T00:00:00-04:00")
PEOPLE = [("ravi", "Ravi", "ravi-iphone", "#e4e1d6"), ("paul", "Paul", "paul-iphone", "#4f9bf5"), ("amy", "Amy", "amy-pixel", "#f47a4a"),
          ("ken", "Ken", "ken-galaxy", "#2fc48d"), ("cara", "Cara", "cara-iphone", "#f0b429")]


def rows(device, name):
    with open(os.path.join(BUNDLE, "devices", device, name + ".jsonl")) as f:
        return [json.loads(line) for line in f]


def minute(ts):
    return round((datetime.fromisoformat(ts) - START).total_seconds() / 60, 2)


manifest = json.load(open(os.path.join(BUNDLE, "manifest.json")))
number_of = {}
for line in open(os.path.join(BUNDLE, "persons.jsonl")):
    p = json.loads(line)
    number_of[next(i["value"] for i in p["identifiers"] if i["kind"] == "phone")] = p["person_id"]
name = {pid: nm for pid, nm, _, _ in PEOPLE}
phones, events, seen = [], [], {}
for pid, nm, device, colour in PEOPLE:
    fixes = [[minute(r["timestamp"]), r["lat"], r["lon"]] for r in rows(device, "locations") if START <= datetime.fromisoformat(r["timestamp"]) <= END]
    power = [[minute(r["timestamp"]), r["event_type"]] for r in rows(device, "device_events")
             if r["event_type"] in ("power_off", "power_on") and START <= datetime.fromisoformat(r["timestamp"]) <= END]
    phones.append(dict(id=pid, name=nm, colour=colour, fixes=fixes, power=power))
    for kind, table, tfield in (("text", "messages", "timestamp"), ("call", "calls", "start_time")):
        for r in rows(device, table):
            t = datetime.fromisoformat(r[tfield])
            a, b = number_of.get(r["from"]["value"]), number_of.get(r["to"][0]["value"])
            if not (a and b and START <= t <= END):
                continue
            key = (kind, a, b, r.get("body", ""), round(minute(r[tfield]) / (3 if kind == "text" else 0.5)))   # the two phones' copies of one event
            e = seen.setdefault(key, dict(t=minute(r[tfield]), kind=kind, frm=a, to=b, holders=[]))
            e["holders"].append(pid)
            if kind == "text":
                e["body"] = r["body"]
                if r.get("received_timestamp") and minute(r["received_timestamp"]) - e["t"] > 5:
                    e["delivered"] = minute(r["received_timestamp"])
            else:
                e["duration_s"], e["status"] = r["duration_s"], r["status"]
events = sorted(seen.values(), key=lambda e: e["t"])
for e in events:
    both = {e["frm"], e["to"]}
    e["only_on"] = e["holders"][0] if len(set(e["holders"])) == 1 and len(both) == 2 else None
with open(os.path.join(HERE, "replay-data.js"), "w") as f:
    f.write("// Generated by build_replay_data.py from data/synthetic/pier9. Do not edit by hand.\nwindow.REPLAY = ")
    json.dump(dict(start="2026-04-16T18:00:00-04:00", minutes=360, window=[180, 330], places=manifest["places"], phones=phones, events=events), f, ensure_ascii=False)
    f.write(";\n")
print(len(events), "events;", {p["id"]: len(p["fixes"]) for p in phones})
for e in events:
    print(f"{int(18 + e['t'] // 60):02d}:{int(e['t'] % 60):02d}", e["kind"], e["frm"], ">", e["to"], "|", e.get("body", f"{e.get('duration_s')}s {e.get('status')}")[:60], "| only on:", e["only_on"], "| delivered:", e.get("delivered"))
